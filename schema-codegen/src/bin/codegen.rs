use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;
use syn::{
    Expr, ExprLit, FnArg, GenericArgument, Item, ItemTrait, Lit, Meta, Pat, PathArguments,
    ReturnType, TraitItem, Type,
};

struct Param {
    name: String,
    ts_type: String,
    docs: Vec<String>,
}

struct Method {
    ts_name: String,
    params: Vec<Param>,
    ret: String,
    docs: Vec<String>,
}

struct Api {
    namespace: String,
    module: String,
    class_name: String,
    docs: Vec<String>,
    methods: Vec<Method>,
}

fn main() {
    let rust_only = std::env::args().skip(1).any(|a| a == "--rust-only");

    let src_dir = Path::new("schema/src");
    let bindings_dir = Path::new("schema/bindings");
    let per_type_dir = bindings_dir.join("_per_type");
    let client_dir = Path::new("schema/client");

    let mut type_to_module: BTreeMap<String, String> = BTreeMap::new();
    let mut module_types: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut apis: Vec<Api> = Vec::new();
    let mut imports: BTreeSet<String> = BTreeSet::new();

    for entry in fs::read_dir(src_dir).expect("read schema/src") {
        let entry = entry.unwrap();
        let path = entry.path();
        if !path.is_file() || path.extension().and_then(|e| e.to_str()) != Some("rs") {
            continue;
        }
        let module = path.file_stem().unwrap().to_string_lossy().into_owned();
        if module == "lib" {
            continue;
        }
        let src = fs::read_to_string(&path).expect("read source file");
        let Ok(file) = syn::parse_file(&src) else {
            continue;
        };
        for item in &file.items {
            match item {
                Item::Struct(s) if has_attr(&s.attrs, "vla_type") => {
                    let name = s.ident.to_string();
                    type_to_module.insert(name.clone(), module.clone());
                    module_types.entry(module.clone()).or_default().push(name);
                }
                Item::Enum(e) if has_attr(&e.attrs, "vla_type") => {
                    let name = e.ident.to_string();
                    type_to_module.insert(name.clone(), module.clone());
                    module_types.entry(module.clone()).or_default().push(name);
                }
                Item::Trait(t) => {
                    if let Some(namespace) = extract_namespace(t) {
                        apis.push(parse_trait(t, namespace, module.clone(), &mut imports));
                    }
                }
                _ => {}
            }
        }
    }

    apis.sort_by(|a, b| a.namespace.cmp(&b.namespace));
    write_into_module(Path::new("schema/src/_generated.rs"), &apis);

    if rust_only {
        return;
    }

    // Clean up legacy bundles from the old client/api.ts + bindings/<module>.ts layout.
    sweep_stale_ts(bindings_dir);
    sweep_stale_ts(client_dir);

    let all_modules: BTreeSet<String> = module_types
        .keys()
        .cloned()
        .chain(apis.iter().map(|a| a.module.clone()))
        .collect();
    for module in &all_modules {
        let types = module_types.get(module).cloned().unwrap_or_default();
        let api = apis.iter().find(|a| &a.module == module);
        write_namespace_file(
            client_dir,
            module,
            &types,
            api,
            &per_type_dir,
            &type_to_module,
        );
    }

    write_index(&client_dir.join("index.ts"), &apis, &type_to_module);
}

fn sweep_stale_ts(dir: &Path) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        if path.extension().and_then(|e| e.to_str()) != Some("ts") {
            continue;
        }
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        // Don't sweep hand-written client files.
        if name == "rpc.ts" {
            continue;
        }
        let _ = fs::remove_file(&path);
    }
}

fn write_into_module(out_path: &Path, apis: &[Api]) {
    let mut out = String::new();
    out.push_str("// Generated by schema-codegen. Do not edit.\n\n");
    out.push_str("use jsonrpsee::core::RegisterMethodError;\n");
    out.push_str("use jsonrpsee::server::RpcModule;\n\n");

    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub fn into_module<T>(api: T) -> Result<RpcModule<T>, RegisterMethodError>\n");
    out.push_str("where\n");
    out.push_str("    T: Clone\n");
    out.push_str("        + Send\n");
    out.push_str("        + Sync\n");
    out.push_str("        + 'static");
    for api in apis {
        out.push_str(&format!(
            "\n        + crate::{module}::{trait_name}Server",
            module = api.module,
            trait_name = api.class_name
        ));
    }
    out.push_str(",\n{\n");

    if apis.is_empty() {
        out.push_str("    Ok(RpcModule::new(api))\n");
    } else if apis.len() == 1 {
        let only = &apis[0];
        out.push_str(&format!(
            "    Ok(<T as crate::{module}::{trait_name}Server>::into_rpc(api))\n",
            module = only.module,
            trait_name = only.class_name
        ));
    } else {
        let (first, rest) = apis.split_first().unwrap();
        out.push_str(&format!(
            "    let mut module = <T as crate::{module}::{trait_name}Server>::into_rpc(api.clone());\n",
            module = first.module,
            trait_name = first.class_name
        ));
        for api in rest {
            out.push_str(&format!(
                "    module.merge(<T as crate::{module}::{trait_name}Server>::into_rpc(api.clone()))?;\n",
                module = api.module,
                trait_name = api.class_name
            ));
        }
        out.push_str("    let _ = api;\n");
        out.push_str("    Ok(module)\n");
    }
    out.push_str("}\n");

    if let Ok(existing) = fs::read_to_string(out_path) {
        if existing == out {
            return;
        }
    }
    fs::write(out_path, out).expect("write _generated.rs");
}

fn write_namespace_file(
    client_dir: &Path,
    module: &str,
    types: &[String],
    api: Option<&Api>,
    per_type_dir: &Path,
    type_to_module: &BTreeMap<String, String>,
) {
    let mut cross_imports: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut type_bodies: Vec<String> = Vec::new();

    for ty in types {
        let file = per_type_dir.join(format!("{ty}.ts"));
        let raw = fs::read_to_string(&file).unwrap_or_else(|_| {
            panic!("missing per-type binding {}", file.display());
        });

        for line in raw.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix("import type { ") {
                let Some(name_end) = rest.find(" }") else {
                    continue;
                };
                let names: Vec<String> = rest[..name_end]
                    .split(',')
                    .map(|s| s.trim().to_string())
                    .filter(|s| !s.is_empty())
                    .collect();
                for name in names {
                    let Some(other_module) = type_to_module.get(&name) else {
                        panic!("imported type {name} not found in any module");
                    };
                    if other_module != module {
                        cross_imports
                            .entry(other_module.clone())
                            .or_default()
                            .insert(name);
                    }
                }
                continue;
            }
            if trimmed.starts_with("import ") || trimmed.starts_with("// This file was generated") {
                continue;
            }
            type_bodies.push(line.to_string());
        }
        type_bodies.push(String::new());
    }

    // Cross-namespace types referenced by this trait's method signatures
    if let Some(api) = api {
        for m in &api.methods {
            for p in &m.params {
                if let Some(other_module) = type_to_module.get(&p.ts_type) {
                    if other_module != module {
                        cross_imports
                            .entry(other_module.clone())
                            .or_default()
                            .insert(p.ts_type.clone());
                    }
                }
            }
            if let Some(other_module) = type_to_module.get(&m.ret) {
                if other_module != module {
                    cross_imports
                        .entry(other_module.clone())
                        .or_default()
                        .insert(m.ret.clone());
                }
            }
        }
    }

    let mut out = String::new();
    out.push_str("// Generated by schema-codegen. Do not edit.\n\n");
    if api.is_some() {
        out.push_str("import { RpcClient } from \"./rpc\";\n");
    }
    for (m, names) in &cross_imports {
        let list = names.iter().cloned().collect::<Vec<_>>().join(", ");
        out.push_str(&format!("import type {{ {list} }} from \"./{m}\";\n"));
    }
    out.push('\n');

    let mut bodies = String::new();
    for line in type_bodies {
        bodies.push_str(&line);
        bodies.push('\n');
    }
    out.push_str(&format_ts(&bodies));
    while out.ends_with("\n\n\n") {
        out.pop();
    }

    if let Some(api) = api {
        emit_sub_class(&mut out, api);
    }

    let dest = client_dir.join(format!("{module}.ts"));
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent).expect("create client dir");
    }
    fs::write(&dest, out).expect("write namespace file");
}

fn write_index(out_path: &Path, apis: &[Api], type_to_module: &BTreeMap<String, String>) {
    let mut out = String::new();
    out.push_str("// Generated by schema-codegen. Do not edit.\n\n");
    out.push_str("import { RpcClient } from \"./rpc\";\n");
    for api in apis {
        out.push_str(&format!(
            "import {{ {cls} }} from \"./{module}\";\n",
            cls = api.class_name,
            module = api.module
        ));
    }
    out.push('\n');

    let modules_with_types: BTreeSet<&String> = type_to_module.values().collect();
    for module in &modules_with_types {
        out.push_str(&format!("export type * from \"./{module}\";\n"));
    }
    if !modules_with_types.is_empty() {
        out.push('\n');
    }

    out.push_str("export class Api {\n");
    out.push_str("\t#rpc: RpcClient;\n");
    for api in apis {
        emit_jsdoc(&mut out, &api.docs, "\t");
        out.push_str(&format!(
            "\t{ns}: {cls};\n",
            ns = api.namespace,
            cls = api.class_name
        ));
    }
    out.push_str("\n\tconstructor(url: string) {\n");
    out.push_str("\t\tthis.#rpc = new RpcClient(url);\n");
    for api in apis {
        out.push_str(&format!(
            "\t\tthis.{ns} = new {cls}(this.#rpc);\n",
            ns = api.namespace,
            cls = api.class_name
        ));
    }
    out.push_str("\t}\n\n");
    out.push_str("\tready(): Promise<void> {\n\t\treturn this.#rpc.ready();\n\t}\n\n");
    out.push_str("\tclose(): void {\n\t\tthis.#rpc.close();\n\t}\n");
    out.push_str("}\n");

    if let Some(parent) = out_path.parent() {
        fs::create_dir_all(parent).expect("create client dir");
    }
    fs::write(out_path, out).expect("write index.ts");
}

fn parse_trait(
    t: &ItemTrait,
    namespace: String,
    module: String,
    imports: &mut BTreeSet<String>,
) -> Api {
    let mut methods = Vec::new();
    for item in &t.items {
        let TraitItem::Fn(method) = item else {
            continue;
        };
        let ts_name = snake_to_camel(&method.sig.ident.to_string());
        let docs = extract_docs(&method.attrs);

        let mut params = Vec::new();
        for arg in &method.sig.inputs {
            let FnArg::Typed(pat) = arg else { continue };
            let name = match &*pat.pat {
                Pat::Ident(p) => p.ident.to_string(),
                _ => panic!("unsupported param pattern in {}", method.sig.ident),
            };
            let ts_type = rust_type_to_ts(&pat.ty, imports);
            let docs = extract_docs(&pat.attrs);
            params.push(Param {
                name,
                ts_type,
                docs,
            });
        }

        let ret = match &method.sig.output {
            ReturnType::Type(_, ty) => extract_rpc_result_inner(ty, imports),
            ReturnType::Default => "void".into(),
        };

        methods.push(Method {
            ts_name,
            params,
            ret,
            docs,
        });
    }
    Api {
        namespace,
        module,
        class_name: t.ident.to_string(),
        docs: extract_docs(&t.attrs),
        methods,
    }
}

fn emit_sub_class(out: &mut String, api: &Api) {
    out.push('\n');
    emit_jsdoc(out, &api.docs, "");
    out.push_str(&format!("export class {} {{\n", api.class_name));
    out.push_str("\t#rpc: RpcClient;\n\n");
    out.push_str("\tconstructor(rpc: RpcClient) {\n\t\tthis.#rpc = rpc;\n\t}\n");

    for m in &api.methods {
        let full = format!("{}_{}", api.namespace, m.ts_name);
        let param_decl = m
            .params
            .iter()
            .map(|p| format!("{}: {}", p.name, p.ts_type))
            .collect::<Vec<_>>()
            .join(", ");
        let param_call = if m.params.is_empty() {
            String::new()
        } else {
            let names = m
                .params
                .iter()
                .map(|p| p.name.clone())
                .collect::<Vec<_>>()
                .join(", ");
            format!(", [{names}]")
        };
        out.push('\n');
        emit_method_jsdoc(out, &m.docs, &m.params, "\t");
        out.push_str(&format!(
            "\t{name}({decl}): Promise<{ret}> {{\n",
            name = m.ts_name,
            decl = param_decl,
            ret = m.ret
        ));
        out.push_str(&format!(
            "\t\treturn this.#rpc.call(\"{full}\"{param_call});\n"
        ));
        out.push_str("\t}\n");
    }
    out.push_str("}\n");
}

fn extract_namespace(t: &ItemTrait) -> Option<String> {
    for attr in &t.attrs {
        if !attr.path().is_ident("vla_api") {
            continue;
        }
        let Meta::List(list) = &attr.meta else {
            continue;
        };
        let parser = syn::punctuated::Punctuated::<Meta, syn::Token![,]>::parse_terminated;
        let metas = match syn::parse::Parser::parse2(parser, list.tokens.clone()) {
            Ok(m) => m,
            Err(_) => continue,
        };
        for meta in metas {
            if let Meta::NameValue(nv) = meta {
                if nv.path.is_ident("namespace") {
                    if let Expr::Lit(ExprLit {
                        lit: Lit::Str(s), ..
                    }) = nv.value
                    {
                        return Some(s.value());
                    }
                }
            }
        }
    }
    None
}

fn has_attr(attrs: &[syn::Attribute], name: &str) -> bool {
    attrs.iter().any(|a| a.path().is_ident(name))
}

fn extract_docs(attrs: &[syn::Attribute]) -> Vec<String> {
    let mut lines = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        let syn::Meta::NameValue(nv) = &attr.meta else {
            continue;
        };
        let syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Str(s),
            ..
        }) = &nv.value
        else {
            continue;
        };
        let text = s.value();
        let trimmed = text.strip_prefix(' ').unwrap_or(&text);
        lines.push(trimmed.to_string());
    }
    lines
}

fn format_ts(content: &str) -> String {
    let mut out = String::new();
    let mut depth: i32 = 0;
    for raw_line in content.lines() {
        let trimmed = raw_line.trim_start();
        let starts_close = trimmed.starts_with('}') || trimmed.starts_with(']');
        let line_depth = if starts_close {
            (depth - 1).max(0)
        } else {
            depth
        };
        if !trimmed.is_empty() {
            for _ in 0..line_depth {
                out.push('\t');
            }
            // Re-add the leading space convention for JSDoc continuation lines.
            if trimmed.starts_with('*') {
                out.push(' ');
            }
            out.push_str(trimmed);
        }
        out.push('\n');
        let opens = trimmed.matches('{').count() as i32 + trimmed.matches('[').count() as i32;
        let closes = trimmed.matches('}').count() as i32 + trimmed.matches(']').count() as i32;
        depth = (depth + opens - closes).max(0);
    }
    out
}

fn emit_jsdoc(out: &mut String, docs: &[String], indent: &str) {
    if docs.is_empty() {
        return;
    }
    if docs.len() == 1 {
        out.push_str(&format!("{indent}/** {} */\n", docs[0]));
        return;
    }
    out.push_str(&format!("{indent}/**\n"));
    for line in docs {
        out.push_str(&format!("{indent} * {line}\n"));
    }
    out.push_str(&format!("{indent} */\n"));
}

fn emit_method_jsdoc(out: &mut String, method_docs: &[String], params: &[Param], indent: &str) {
    let has_method = !method_docs.is_empty();
    let has_params = params.iter().any(|p| !p.docs.is_empty());
    if !has_method && !has_params {
        return;
    }
    if has_method && !has_params && method_docs.len() == 1 {
        out.push_str(&format!("{indent}/** {} */\n", method_docs[0]));
        return;
    }
    out.push_str(&format!("{indent}/**\n"));
    for line in method_docs {
        out.push_str(&format!("{indent} * {line}\n"));
    }
    for p in params {
        if p.docs.is_empty() {
            continue;
        }
        let summary = p.docs.join(" ");
        out.push_str(&format!("{indent} * @param {} - {summary}\n", p.name));
    }
    out.push_str(&format!("{indent} */\n"));
}

fn snake_to_camel(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut upper = false;
    for c in s.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn rust_type_to_ts(ty: &Type, imports: &mut BTreeSet<String>) -> String {
    match ty {
        Type::Tuple(t) if t.elems.is_empty() => "void".into(),
        Type::Path(p) => {
            let seg = p.path.segments.last().unwrap();
            let name = seg.ident.to_string();
            match name.as_str() {
                "String" | "str" => "string".into(),
                "bool" => "boolean".into(),
                "u8" | "u16" | "u32" | "u64" | "usize" | "i8" | "i16" | "i32" | "i64" | "isize"
                | "f32" | "f64" => "number".into(),
                "Vec" => {
                    let inner = first_generic(&seg.arguments)
                        .map(|t| rust_type_to_ts(t, imports))
                        .unwrap_or_else(|| "unknown".into());
                    format!("{inner}[]")
                }
                "Option" => {
                    let inner = first_generic(&seg.arguments)
                        .map(|t| rust_type_to_ts(t, imports))
                        .unwrap_or_else(|| "unknown".into());
                    format!("{inner} | null")
                }
                _ => {
                    imports.insert(name.clone());
                    name
                }
            }
        }
        _ => "unknown".into(),
    }
}

fn extract_rpc_result_inner(ty: &Type, imports: &mut BTreeSet<String>) -> String {
    if let Type::Path(p) = ty {
        let seg = p.path.segments.last().unwrap();
        if seg.ident == "RpcResult" {
            if let Some(inner) = first_generic(&seg.arguments) {
                return rust_type_to_ts(inner, imports);
            }
        }
    }
    rust_type_to_ts(ty, imports)
}

fn first_generic(args: &PathArguments) -> Option<&Type> {
    if let PathArguments::AngleBracketed(a) = args {
        for arg in &a.args {
            if let GenericArgument::Type(t) = arg {
                return Some(t);
            }
        }
    }
    None
}
